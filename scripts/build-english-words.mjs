// Writes workers/english-words.mjs: the English words a disc-name typo could land on. A word the
// player typed on purpose ("time", "lost", "page") must never be read as a mold one letter away
// ("Tide", "Lots", "Pace"), so the matcher skips typo matching for these words.
//
// Source: the system word list (/usr/share/dict/words, Webster's 2nd on macOS), lowercase entries
// only, plus EXTRA for modern words it lacks. Kept: every word that is within the matcher's typo
// allowance of a catalog name with the same first letter, in itself or in a common inflection.
// Rerun after the catalog gains molds: node scripts/build-english-words.mjs
import {readFileSync, writeFileSync} from 'node:fs';
import catalog from '../public/data.json' with {type: 'json'};
import {editDistance, fold, typoAllowance} from '../workers/disc-names.mjs';

const EXTRA = 'stat stats okay email online app apps video videos youtube website blog vlog pdga ratings rated tbh lol idk'.split(' ');
const dict = readFileSync(process.argv[2] || '/usr/share/dict/words', 'utf8').split('\n').filter(w => /^[a-z]{4,14}$/.test(w));
const keys = new Map();
for (const disc of catalog.discs) for (const text of [disc.name, disc.name.replace(/[(（][^)）]*[)）]?/g, ' '), disc.catalogName, ...(disc.aliases || [])]) {
 const tokens = fold(text).match(/[\p{L}\p{N}]+/gu) || [], key = tokens.join('');
 if (key.length >= 4 && tokens.length <= 2) {const bucket = key[0]; if (!keys.has(bucket)) keys.set(bucket, new Set()); keys.get(bucket).add(key);}
}
const forms = w => [w, w + 's', w + 'es', w + 'ed', w + 'd', w + 'ing', w.replace(/e$/, '') + 'ing', w + 'er', w + 'y'];
const near = w => [...keys.get(w[0]) || []].some(k => {const max = Math.min(typoAllowance(w.length), typoAllowance(k.length)); return max && Math.abs(k.length - w.length) <= max && editDistance(w, k, max) <= max;});
const words = [...new Set([...dict, ...EXTRA])].filter(w => forms(w).some(near)).sort();
writeFileSync(new URL('../workers/english-words.mjs', import.meta.url), `// Generated by scripts/build-english-words.mjs from the system word list; do not edit by hand.
// English words a typo away from a catalog disc name: typos never turn these into molds.
export default new Set(${JSON.stringify(words.join(' '))}.split(' '));
`);
console.log(`${words.length} words`);
